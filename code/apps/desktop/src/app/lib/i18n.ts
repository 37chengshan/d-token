export const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "zh",
  setLang: () => {},
});

export function useI18n() {
  return useContext(I18nContext);
}

export function useT() {
  const { lang } = useI18n();
  return (key: string, values?: CopyValues) => translateCopy(key, lang, values);
}

/**
 * Formats the product-owned bilingual copy without ever interpolating a
 * missing value as an opaque object. Dynamic names and counts stay explicit
 * at the call site while the surrounding sentence remains centrally owned.
 */
export function translateCopy(key: string, lang: Lang, values?: CopyValues) {
  const entry = DICT[key];
  const template = entry ? entry[lang] : key;
  return formatCopy(template, values);
}

export function formatCopy(template: string, values?: CopyValues) {
  if (!values) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (token, key: string) => {
    const value = values[key];
    return value === undefined || value === null ? token : String(value);
  });
}
