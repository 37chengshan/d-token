pub fn glyph(character: char) -> [u8; 8] {
    if (' '..='~').contains(&character) {
        SPLEEN_5X8_ASCII[character as usize - 32]
    } else if character == '↵' {
        [0, 32, 32, 40, 248, 8, 16, 0]
    } else {
        SPLEEN_5X8_ASCII['?' as usize - 32]
    }
}

